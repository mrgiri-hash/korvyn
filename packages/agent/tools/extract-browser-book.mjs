/**
 * ONE-BOOK SEED EXTRACTOR (Phase 3D).
 *
 * The browser prototype (index.html) and the server used to carry SEPARATE fixtures for the same close checklist,
 * reconciliation review states, Flux statement lines and saved reports. This script lifts those fixtures out of
 * index.html ONCE into `src/sloane/persistence/browser-book.json`, which the server seed writes into the durable work
 * store. From then on the SERVER is the book: the browser reads it through /api/work/* and never writes its own copy.
 *
 * Run from packages/agent:  node tools/extract-browser-book.mjs
 * Re-run only when the browser's seed fixtures change; the output is committed and deterministic.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, '..', '..', '..', 'index.html'), 'utf8').replace(/\r\n/g, '\n');

/** the literal that starts at `start` and ends at the first line that is exactly `end` */
function literal(start, end) {
  const a = html.indexOf(start);
  if (a < 0) throw new Error(`not found: ${start}`);
  const b = html.indexOf(`\n${end}\n`, a);
  if (b < 0) throw new Error(`no terminator ${end} after ${start}`);
  return html.slice(a + start.length - 1, b + 1 + end.length - 1);
}
const evalLit = (src, names = [], vals = []) => new Function(...names, `return (${src});`)(...vals);

const closeTasks = evalLit(literal('const CLOSE_TASKS=[', '];'));
const rcSeed = evalLit(literal('const RC_SEED={', '};'));
const fsLines = evalLit(literal('const FSLINES=[', '];'));
const fnStart = html.indexOf('function rbSeedDef(o){');
const fnEnd = html.indexOf('\n}\n', fnStart);
const rbSeedDef = new Function(`${html.slice(fnStart, fnEnd + 2)}; return rbSeedDef;`)();
const reports = evalLit(literal('const RB_REPORTS=[', '];'), ['rbSeedDef'], [rbSeedDef]);

const out = {
  generatedFrom: 'index.html',
  note: 'Generated by tools/extract-browser-book.mjs. The server seeds these into the durable work store; the browser reads them back through /api/work/*.',
  closeTasks,
  reconciliationReview: rcSeed,
  /* the Flux Review workspace presents the governed statement lines (FS-CIP …): these are its line ids */
  fluxLines: fsLines.map((l) => ({ id: l.id, name: l.name.replace(/&amp;/g, '&'), parent: l.parent, kind: l.kind })),
  reports,
};
writeFileSync(join(here, '..', 'src', 'sloane', 'persistence', 'browser-book.json'), JSON.stringify(out, null, 1) + '\n');
console.log(`close tasks ${closeTasks.length} · reconciliation review states ${Object.keys(rcSeed).length} · flux lines ${out.fluxLines.length} · reports ${reports.length}`);
